const { contextBridge, ipcRenderer } = require("electron");

contextBridge.exposeInMainWorld("brujula", {
  macUpdates: () => ipcRenderer.invoke("browser:mac-updates"),
  appUpdateAction: (action) => ipcRenderer.invoke("browser:app-update", action),
  setBrowserPreferences: (patch) => ipcRenderer.invoke("browser:set-browser-preferences", patch),
  runCommand: (id) => ipcRenderer.invoke("browser:run-command", id),
  acceptLegal: (input) => ipcRenderer.invoke("browser:accept-legal", input),
  quit: () => ipcRenderer.invoke("browser:quit"),
  getState: () => ipcRenderer.invoke("browser:get-state"),
  setProtectedVideo: (enabled) => ipcRenderer.invoke("browser:set-protected-video", enabled),
  checkProtectedVideo: () => ipcRenderer.invoke("browser:check-protected-video"),
  onPanelDismissed: (callback) => { ipcRenderer.on("browser:panel-dismissed", () => callback()); },
  downloadAction: (id, action) => ipcRenderer.invoke("browser:download-action", id, action),
  onDownloadStarted: (callback) => { ipcRenderer.on("browser:download-started", (_event, value) => callback(value)); },
  uiReady: () => ipcRenderer.invoke("browser:ui-ready"),
  featureAction: (action) => ipcRenderer.invoke("browser:feature-action", action),
  newTab: () => ipcRenderer.invoke("browser:new-tab"),
  showTabsMenu: () => ipcRenderer.invoke("browser:show-tabs-menu"),
  activateTab: (id) => ipcRenderer.invoke("browser:activate-tab", id),
  closeTab: (id) => ipcRenderer.invoke("browser:close-tab", id),
  navigate: (value) => ipcRenderer.invoke("browser:navigate", value),
  search: (value) => ipcRenderer.invoke("browser:search", value),
  searchSuggestions: (input) => ipcRenderer.invoke("browser:search-suggestions", input),
  cancelSearchSuggestions: () => ipcRenderer.invoke("browser:cancel-search-suggestions"),
  back: () => ipcRenderer.invoke("browser:back"),
  forward: () => ipcRenderer.invoke("browser:forward"),
  reload: () => ipcRenderer.invoke("browser:reload"),
  stop: () => ipcRenderer.invoke("browser:stop"),
  home: () => ipcRenderer.invoke("browser:home"),
  addBookmark: () => ipcRenderer.invoke("browser:add-bookmark"),
  removeBookmark: (url) => ipcRenderer.invoke("browser:remove-bookmark", url),
  openUrl: (url) => ipcRenderer.invoke("browser:open-url", url),
  restoreClosed: () => ipcRenderer.invoke("browser:restore-closed"),
  clearHistory: () => ipcRenderer.invoke("browser:clear-history"),
  setPanelOpen: (open) => ipcRenderer.invoke("browser:set-panel-open", open),
  setAddressPopupHeight: (height) => ipcRenderer.invoke("browser:set-address-popup-height", height),
  onAddressDismissed: (callback) => ipcRenderer.on("browser:address-dismissed", () => callback()),
  setTitlebarRevealed: (revealed) => ipcRenderer.invoke("browser:set-titlebar-revealed", revealed),
  setAppearance: (patch) => ipcRenderer.invoke("browser:set-appearance", patch),
  resetAppearance: () => ipcRenderer.invoke("browser:reset-appearance"),
  togglePageThemeSite: () => ipcRenderer.invoke("browser:toggle-page-theme-site"),
  resetPageThemeSites: () => ipcRenderer.invoke("browser:reset-page-theme-sites"),
  chooseBackgroundVideo: () => ipcRenderer.invoke("browser:choose-background-video"),
  selectBackgroundVideo: (fileName) => ipcRenderer.invoke("browser:select-background-video", fileName),
  clearBackgroundVideo: () => ipcRenderer.invoke("browser:clear-background-video"),
  updateFilters: () => ipcRenderer.invoke("browser:update-filters"),
  toggleSiteProtection: () => ipcRenderer.invoke("browser:toggle-site-protection"),
  rememberHistory: (enabled) => ipcRenderer.invoke("browser:remember-history", enabled),
  clearSiteData: () => ipcRenderer.invoke("browser:clear-site-data"),
  onState: (callback) => ipcRenderer.on("browser:state", (_event, state) => callback(state)),
  onNotice: (callback) => ipcRenderer.on("browser:notice", (_event, message) => callback(message)),
  onFocusAddress: (callback) => ipcRenderer.on("browser:focus-address", () => callback()),
});
